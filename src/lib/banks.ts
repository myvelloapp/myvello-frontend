/**
 * Searches for a bank matching a query string (name, shortName, id, keywords, or domain).
 */
export function findBank(query: string): BankInfo | undefined {
  if (!query) return undefined;
  const q = query.toLowerCase().trim();

  // 1. Direct match
  const exact = INDIAN_BANKS.find(
    (b) =>
      b.name.toLowerCase() === q ||
      b.shortName.toLowerCase() === q ||
      b.id.toLowerCase() === q
  );
  if (exact) return exact;

  // 2. Partial / Substring / Keyword match
  return INDIAN_BANKS.find((b) => {
    const nameMatch = b.name.toLowerCase().includes(q) || q.includes(b.name.toLowerCase());
    const shortMatch = b.shortName.toLowerCase().includes(q) || q.includes(b.shortName.toLowerCase());
    const domainMatch = b.domain ? q.includes(b.domain.toLowerCase()) : false;
    const keywordMatch = b.keywords ? b.keywords.some((k) => q.includes(k) || k.includes(q)) : false;
    return nameMatch || shortMatch || domainMatch || keywordMatch;
  });
}

/**
 * Get the logo URL for any bank name string.
 */
export function getBankLogoUrl(name: string): string | undefined {
  const bank = findBank(name);
  if (bank) return bank.logoUrl;
  return undefined;
}
